#!/usr/bin/env python3
"""draft.py — Option A chain caller. Produce a journal-style manuscript skeleton
from biostats artifacts in cwd.

Pipeline:
  1. Glob detect biostats artifacts in cwd (table1 xlsx, KM/forest png, analysis_log.json).
  2. (User-managed) Call `manuscript-results` skill from Claude to populate prose.
     This script writes a placeholder Results section and notes the chain step.
  3. Wrap the output with the journal's prompt.md voice.
  4. Output `manuscript_<journal>.md` + `figures/` dir of restyled figures.

Note: the `manuscript-results` chain is performed by Claude (the SKILL.md
reasoning agent), not by this script — Python cannot invoke another Skill.
This script does the deterministic file work; Claude weaves the prose.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

_THIS_DIR = Path(__file__).resolve().parent
_PKG_DIR = _THIS_DIR.parent
if str(_PKG_DIR) not in sys.path:
    sys.path.insert(0, str(_PKG_DIR))

from core.theme_loader import load_spec, list_journals  # noqa: E402

ARTIFACT_GLOBS = [
    "*table1*.xlsx", "*Table1*.xlsx", "*baseline*.xlsx",
    "*km*.png", "*kaplan*.png", "*survival*.png",
    "*forest*.png", "*forest*.xlsx",
    "*cif*.png", "*competing*.png",
    "*love*.png", "*psm*.png", "*psm*.xlsx",
    "*flowchart*.png", "*consort*.png",
    "*roc*.png", "*auc*.xlsx",
    "analysis_log.json", "research_plan.json",
]


def discover_artifacts(cwd: Path) -> list[Path]:
    found: list[Path] = []
    for pat in ARTIFACT_GLOBS:
        found.extend(cwd.glob(pat))
        found.extend(cwd.glob(f"*/{pat}"))
    return sorted(set(found))


def render_skeleton(journal: str, artifacts: list[Path], out_path: Path) -> None:
    spec = load_spec(journal)
    j = spec["journal"]
    prompt_path = Path(spec["_journal_dir"]) / "prompt.md"
    voice = prompt_path.read_text(encoding="utf-8") if prompt_path.is_file() else ""

    artifact_block = "\n".join(f"- {p.name}" for p in artifacts) or "  (none detected)"

    body = f"""---
journal: {j['short']}
journal_full_name: {j['name']}
spec_version: {j['spec_version']}
generated_by: academic-style/scripts/draft.py
---

# {j['name']} Manuscript Skeleton

> Generated by academic-style draft mode. Replace placeholder sections with content
> drafted via the `manuscript-results` skill (Claude can chain that automatically when
> this skill is invoked through `/academic-style {j['short']} --draft`).

## Detected biostats artifacts

{artifact_block}

## Title

[Title — see {j['short']}/prompt.md for the journal's case style]

## Abstract

[Insert abstract per the journal's structured / unstructured format. Voice & word
count rules in `journals/{j['short']}/prompt.md`.]

## Introduction

[1-3 paragraphs.]

## Methods

[Cohort, design, statistical approach. Cite Table 1 for baseline characteristics.]

## Results

[**Chain step**: ask Claude to invoke the `manuscript-results` skill on the cwd
artifacts above. Paste the returned Results section here, then apply the journal's
numeric formatting rules (decimal separator, p-value notation) per `prompt.md`.]

## Discussion

[3-5 paragraphs.]

## Figure captions

[Use the caption template from `journals/{j['short']}/spec.yaml` →
`caption.template`. For each figure in `figures/`, write a caption that matches
the journal's case style and panel-label convention.]

## Cover letter outline

[See `journals/{j['short']}/prompt.md` § Cover letter.]

---

## Voice reference (from prompt.md)

{voice}
"""
    out_path.write_text(body, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Draft a journal-style manuscript skeleton.")
    parser.add_argument(
        "--journal", "--style",
        required=True, choices=list_journals(),
        help="Target journal short name",
    )
    parser.add_argument(
        "--cwd", default=".",
        help="Directory to scan for biostats artifacts (default: cwd)",
    )
    parser.add_argument(
        "--out", default=None,
        help="Output markdown path (default: manuscript_<journal>.md)",
    )
    parser.add_argument(
        "--copy-figures", action="store_true",
        help="Also copy detected PNG/SVG figures into figures/ dir",
    )
    args = parser.parse_args(argv)

    cwd = Path(args.cwd).resolve()
    artifacts = discover_artifacts(cwd)
    out = Path(args.out) if args.out else cwd / f"manuscript_{args.journal}.md"
    render_skeleton(args.journal, artifacts, out)

    if args.copy_figures:
        fig_dir = cwd / "figures"
        fig_dir.mkdir(exist_ok=True)
        for p in artifacts:
            if p.suffix.lower() in {".png", ".svg", ".pdf"}:
                shutil.copy2(p, fig_dir / p.name)

    print(f"Wrote {out} (detected {len(artifacts)} artifacts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
